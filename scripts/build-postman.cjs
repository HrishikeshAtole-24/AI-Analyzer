  req(`Enable ${fault} (${svc})`, 'PUT', base, `admin/faults/${fault}`, body, { expect: [200] });
const disable = (fault, base, svc) =>
  req(`Disable ${fault} (${svc})`, 'DELETE', base, `admin/faults/${fault}`, undefined, { expect: [200] });

