function req(name, method, base, urlPath, body, opts = {}) {
  const [pathPart, queryPart] = urlPath.split('?');
  const query = queryPart
    ? queryPart.split('&').map((q) => {
        const [key, value] = q.split('=');
        return { key, value };
      })
    : undefined;
  const item = {
    name,
    request: {
      method,
      header: body !== undefined ? [{ key: 'Content-Type', value: 'application/json' }] : [],
      url: {
        raw: `{{${base}}}/${urlPath}`,
        host: [`{{${base}}}`],
        path: pathPart.split('/').filter(Boolean),
        ...(query ? { query } : {}),
      },
      ...(opts.description ? { description: opts.description } : {}),
      ...(body !== undefined
        ? { body: { mode: 'raw', raw: JSON.stringify(body, null, 2), options: { raw: { language: 'json' } } } }
        : {}),
    },
  };
  const exec = [];
  if (opts.expect) {
    exec.push(
      `pm.test('status is ${opts.expect.join(' or ')}', () => pm.expect(pm.response.code).to.be.oneOf([${opts.expect.join(', ')}]));`,
    );
  }
  if (opts.save) {
    exec.push('const body = pm.response.json();');
    for (const [variable, field] of Object.entries(opts.save)) {
      exec.push(`if (body.${field}) pm.collectionVariables.set('${variable}', body.${field});`);
    }
  }
  if (opts.script) {
    if (!opts.save) exec.push('const body = pm.response.json();');
    exec.push(...opts.script);
  }
  if (exec.length) item.event = [{ listen: 'test', script: { type: 'text/javascript', exec } }];
  return item;
}

